/*
 * Elliptic-curve arithmetic on the toy curve y^2 = x^3 + 7 (mod 17), G = (1, 5).
 * Every number is a BigInt. Educational code only: never use it with real keys.
 */
(function (root) {
  // The point at infinity O is the neutral element of the group: P + O = P.
  const INFINITY = null;

  const mod = (value, modulus) => ((value % modulus) + modulus) % modulus;

  // Extended Euclidean algorithm: returns v such that value * v = 1 (mod modulus).
  const modInverse = (value, modulus) => {
    let [oldR, r] = [mod(value, modulus), modulus];
    let [oldS, s] = [1n, 0n];
    while (r !== 0n) {
      const quotient = oldR / r;
      [oldR, r] = [r, oldR - quotient * r];
      [oldS, s] = [s, oldS - quotient * s];
    }
    if (oldR !== 1n) throw new RangeError(`${value} has no inverse modulo ${modulus}`);
    return mod(oldS, modulus);
  };

  const point = (x, y) => ({ x: BigInt(x), y: BigInt(y) });

  const TOY_CURVE = { name: 'toy', p: 17n, a: 0n, b: 7n, G: point(1, 5) };

  const isInfinity = (P) => P === INFINITY;

  const equals = (P, Q) => {
    if (isInfinity(P) || isInfinity(Q)) return isInfinity(P) && isInfinity(Q);
    return P.x === Q.x && P.y === Q.y;
  };

  const isOnCurve = (curve, P) => {
    if (isInfinity(P)) return true;
    const { p, a, b } = curve;
    return mod(P.y * P.y - (P.x * P.x * P.x + a * P.x + b), p) === 0n;
  };

  const negate = (curve, P) => (isInfinity(P) ? INFINITY : point(P.x, mod(-P.y, curve.p)));

  // Chord-and-tangent rule. Also returns the case and the slope lambda for the visualisation.
  const addDetailed = (curve, P, Q) => {
    const { p, a } = curve;
    if (isInfinity(P)) return { result: Q, rule: 'identity' };
    if (isInfinity(Q)) return { result: P, rule: 'identity' };
    if (P.x === Q.x && mod(P.y + Q.y, p) === 0n) return { result: INFINITY, rule: 'inverse' };

    const rule = equals(P, Q) ? 'double' : 'add';
    const lambda = rule === 'double'
      ? mod((3n * P.x * P.x + a) * modInverse(2n * P.y, p), p) // tangent
      : mod((Q.y - P.y) * modInverse(Q.x - P.x, p), p); // chord

    const x3 = mod(lambda * lambda - P.x - Q.x, p);
    const y3 = mod(lambda * (P.x - x3) - P.y, p);
    return { result: point(x3, y3), rule, lambda };
  };

  const add = (curve, P, Q) => addDetailed(curve, P, Q).result;

  // Method from the assignment: G, 2G = G + G, 3G = 2G + G, ..., kG.
  const multiplesUpTo = (curve, k, P = curve.G) => {
    const multiples = [];
    let current = INFINITY;
    for (let i = 1n; i <= BigInt(k); i += 1n) {
      current = add(curve, current, P);
      multiples.push({ k: i, point: current });
    }
    return multiples;
  };

  // Faster method: left-to-right double-and-add, O(log k) operations.
  const scalarMultiply = (curve, k, P = curve.G, { trace = false } = {}) => {
    const scalar = BigInt(k);
    const steps = [];
    if (scalar === 0n || isInfinity(P)) return { result: INFINITY, steps };

    const bits = scalar.toString(2);
    let R = INFINITY;
    let multiple = 0n;
    for (let index = 0; index < bits.length; index += 1) {
      const bit = bits[index];
      if (multiple > 0n) {
        const previous = R;
        const { result, lambda, rule } = addDetailed(curve, R, R);
        R = result;
        multiple *= 2n;
        if (trace) steps.push({ op: 'double', rule, bitIndex: index, bit, from: previous, operand: previous, result: R, lambda, multiple });
      }
      if (bit === '1') {
        const previous = R;
        const { result, lambda, rule } = addDetailed(curve, R, P);
        R = result;
        multiple += 1n;
        if (trace) steps.push({ op: multiple === 1n ? 'start' : 'add', rule, bitIndex: index, bit, from: previous, operand: P, result: R, lambda, multiple });
      }
    }
    return { result: R, steps, bits };
  };

  const enumeratePoints = (curve) => {
    const points = [];
    for (let x = 0n; x < curve.p; x += 1n) {
      for (let y = 0n; y < curve.p; y += 1n) {
        if (isOnCurve(curve, point(x, y))) points.push(point(x, y));
      }
    }
    return points;
  };

  // Smallest m > 0 with mP = O: the size of the subgroup generated by P.
  const pointOrder = (curve, P) => {
    let current = P;
    let order = 1n;
    while (!isInfinity(current)) {
      current = add(curve, current, P);
      order += 1n;
    }
    return order;
  };

  const formatPoint = (P) => (isInfinity(P) ? 'O' : `(${P.x}, ${P.y})`);

  root.ECC = {
    INFINITY, TOY_CURVE, mod, modInverse, point, isInfinity, equals, isOnCurve, negate,
    add, addDetailed, multiplesUpTo, scalarMultiply, enumeratePoints, pointOrder, formatPoint
  };
})(window);
